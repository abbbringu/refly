#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$ROOT_DIR/.env"
FORCE=false
START_DOCKER=false

for arg in "$@"; do
  case "$arg" in
    --force) FORCE=true ;;
    --start) START_DOCKER=true ;;
    -h|--help)
      echo "Usage: ./scripts/setup.sh [--force] [--start]"
      echo ""
      echo "Generates a local .env file with fresh Postgres & JWT secrets for Refly."
      echo "  --force   Overwrite an existing .env file"
      echo "  --start   Immediately run 'docker compose up -d --build' after setup"
      exit 0
      ;;
  esac
done

echo ""
echo "Refly — Local Self-Hosted Setup"
echo "──────────────────────────────────────────"

if ! command -v docker >/dev/null 2>&1; then
  echo "Error: Docker is not installed or not in PATH."
  echo "Install Docker Desktop (https://www.docker.com/products/docker-desktop/) and try again."
  exit 1
fi

if ! docker info >/dev/null 2>&1; then
  echo "Warning: Docker daemon does not appear to be running. Start Docker Desktop before running 'docker compose up'."
fi

if [ -f "$ENV_FILE" ] && [ "$FORCE" = false ]; then
  echo ".env already exists at $ENV_FILE (use --force to regenerate)."
else
  if command -v node >/dev/null 2>&1; then
    GENERATED="$(node -e '
      const crypto = require("crypto");
      const pgPassword = crypto.randomBytes(24).toString("hex");
      const jwtSecret = crypto.randomBytes(32).toString("hex");
      function sign(payload) {
        const header = Buffer.from(JSON.stringify({ alg: "HS256", typ: "JWT" })).toString("base64url");
        const body = Buffer.from(JSON.stringify(payload)).toString("base64url");
        const sig = crypto.createHmac("sha256", jwtSecret).update(`${header}.${body}`).digest("base64url");
        return `${header}.${body}.${sig}`;
      }
      const now = Math.floor(Date.now() / 1000);
      const exp = now + 60 * 60 * 24 * 365 * 10;
      console.log(`POSTGRES_PASSWORD=${pgPassword}`);
      console.log(`JWT_SECRET=${jwtSecret}`);
      console.log(`ANON_KEY=${sign({ role: "anon", iss: "supabase", iat: now, exp })}`);
      console.log(`SERVICE_ROLE_KEY=${sign({ role: "service_role", iss: "supabase", iat: now, exp })}`);
    ')"
    POSTGRES_PASSWORD="$(echo "$GENERATED" | grep '^POSTGRES_PASSWORD=' | cut -d= -f2)"
    JWT_SECRET="$(echo "$GENERATED" | grep '^JWT_SECRET=' | cut -d= -f2)"
    ANON_KEY="$(echo "$GENERATED" | grep '^ANON_KEY=' | cut -d= -f2)"
    SERVICE_ROLE_KEY="$(echo "$GENERATED" | grep '^SERVICE_ROLE_KEY=' | cut -d= -f2)"
  else
    # Fallback to local-dev defaults if Node.js is not installed on the host
    POSTGRES_PASSWORD="refly-local-postgres-password"
    JWT_SECRET="refly-local-dev-jwt-secret-change-me-32chars"
    ANON_KEY="eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJyb2xlIjoiYW5vbiIsImlzcyI6InN1cGFiYXNlIiwiaWF0IjoxNzM1Njg5NjAwLCJleHAiOjIwNTEyMjI0MDB9.Frw2CP5sopsDj3cqfRfincYWOWHhaAssOmkTzJe4a0k"
    SERVICE_ROLE_KEY="eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJyb2xlIjoic2VydmljZV9yb2xlIiwiaXNzIjoic3VwYWJhc2UiLCJpYXQiOjE3MzU2ODk2MDAsImV4cCI6MjA1MTIyMjQwMH0.fGc7AzwcPfP5VZ6N3PLfW_j1UIflZhBMNBZgYx3T_PY"
  fi

  cat > "$ENV_FILE" <<EOF
# ============================================================
# Refly — Local Self-Hosted Configuration
# Generated by scripts/setup.sh
# ============================================================

# Open-source self-hosted mode (unlocks all features, disables Stripe billing)
NEXT_PUBLIC_SELF_HOSTED=true

# Ports
REFLY_PORT=3000
SUPABASE_PORT=8000
POSTGRES_PORT=54322

# Public URLs
NEXT_PUBLIC_APP_URL=http://localhost:3000
NEXT_PUBLIC_SUPABASE_URL=http://localhost:8000

# Local Postgres & Auth secrets (auto-generated)
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
JWT_SECRET=${JWT_SECRET}
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${ANON_KEY}
SUPABASE_SERVICE_ROLE_KEY=${SERVICE_ROLE_KEY}

# Direct Postgres connection (for Prisma / local scripts)
DATABASE_URL=postgresql://postgres:${POSTGRES_PASSWORD}@localhost:54322/postgres

# ── Optional AI Features ────────────────────────────────────
# Refly works out of the box without any AI keys (library, PDFs, notes,
# citations, BibTeX/RIS import & export, teams).
#
# To enable AI Chat, Auto-Summaries, Auto-Tagging, and Semantic Search:
# - Set OPENROUTER_API_KEY for multi-model chat (GPT, Claude, Gemini, etc.)
# - Set OPENAI_API_KEY for embeddings (or both chat + embeddings!)
# - Or set AI_CHAT_BASE_URL=http://host.docker.internal:11434/v1 for Ollama
OPENROUTER_API_KEY=
OPENAI_API_KEY=
OPENROUTER_CHAT_MODEL=openai/gpt-5.4
OPENAI_EMBEDDING_MODEL=text-embedding-3-large
OPENAI_EMBEDDING_DIMENSIONS=3072
# AI_CHAT_BASE_URL=
# AI_CHAT_API_KEY=
# AI_CHAT_MODEL=
# OPENAI_BASE_URL=
EOF

  echo "Created $ENV_FILE with fresh local secrets."
fi

echo ""
echo "Next steps:"
echo "  1. (Optional) Add OPENAI_API_KEY / OPENROUTER_API_KEY to .env to enable AI features."
echo "  2. Start Refly with Docker:"
echo "       docker compose up -d --build"
echo "  3. Open http://localhost:3000 and create your local account!"
echo ""

if [ "$START_DOCKER" = true ]; then
  echo "Starting Refly via Docker Compose..."
  cd "$ROOT_DIR"
  docker compose up -d --build
fi
